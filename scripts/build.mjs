import { mkdir, readdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { contentTypeFor } from '../server/security.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const publicDir = path.join(root, 'public');
const dist = path.join(root, 'dist');
const manifestPath = path.join(root, '.openai', 'hosting.json');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
if (!manifest.project_id) throw new Error('.openai/hosting.json needs the registered project_id.');
if (manifest.static) throw new Error('The checkout API requires a Worker deployment; remove static from hosting.json.');

async function walk(directory, relative = '') {
  const assets = {};
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const file = path.join(directory, entry.name);
    const key = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) Object.assign(assets, await walk(file, key));
    else if (entry.isFile()) {
      // Keep original generated artwork in source; serve the optimized WebP files.
      if (key.endsWith('.png')) continue;
      const buffer = await readFile(file);
      const type = contentTypeFor(file);
      const text = type.startsWith('text/') || /json|svg|xml/.test(type);
      assets['/' + key] = {
        data: buffer.toString(text ? 'utf8' : 'base64'),
        binary: !text,
        type,
        size: buffer.length,
        etag: '"' + createHash('sha256').update(buffer).digest('hex').slice(0, 24) + '"',
      };
    }
  }
  return assets;
}

const assets = await walk(publicDir);
if (!assets['/index.html']) throw new Error('public/index.html is missing.');
const [security, commerce, newsletter] = await Promise.all([
  readFile(path.join(root, 'server/security.mjs'), 'utf8'),
  readFile(path.join(root, 'server/commerce.mjs'), 'utf8'),
  readFile(path.join(root, 'server/newsletter.mjs'), 'utf8'),
]);
const source = `// Generated by scripts/build.mjs. Edit public/ and server/ instead.\n${security}\n${commerce}\n${newsletter}\nconst bundledAssets = ${JSON.stringify(assets)};\n
async function serveAsset(request) {
  if (!['GET', 'HEAD'].includes(request.method)) {
    return new Response('Method not allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
  }
  let pathname;
  try { pathname = decodeURIComponent(new URL(request.url).pathname); }
  catch { return new Response('Bad request', { status: 400 }); }
  if (pathname.includes('\\\\') || pathname.includes('\\0') || pathname.split('/').some(part => part.startsWith('.'))) {
    return new Response('Not found', { status: 404 });
  }
  const asset = bundledAssets[pathname === '/' ? '/index.html' : pathname];
  if (!asset) return new Response('Not found', { status: 404 });
  const headers = {
    'Content-Type': asset.type,
    'Cache-Control': pathname === '/' || pathname === '/index.html' ? 'no-cache' : 'public, max-age=3600',
    ETag: asset.etag,
  };
  if (request.headers.get('If-None-Match') === asset.etag) return new Response(null, { status: 304, headers });
  const body = asset.binary ? Uint8Array.from(atob(asset.data), char => char.charCodeAt(0)) : asset.data;
  return new Response(request.method === 'HEAD' ? null : body, { headers });
}

export default {
  async fetch(request, env) {
    try {
      const pathname = new URL(request.url).pathname;
      const response = pathname === '/api' || pathname.startsWith('/api/')
        ? (await handleNewsletter(request, env) || await handleCommerce(request, env) || new Response('Not found', { status: 404 }))
        : await serveAsset(request);
      return secureResponse(response, request);
    } catch {
      return secureResponse(new Response(JSON.stringify({ error: 'Something went wrong. Please try again.' }), {
        status: 500, headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' },
      }), request);
    }
  },
};\n`;
await rm(dist, { recursive: true, force: true });
await mkdir(path.join(dist, 'server'), { recursive: true });
await mkdir(path.join(dist, '.openai'), { recursive: true });
const workerPath = path.join(dist, 'server/index.js');
await writeFile(workerPath + '.tmp', source);
await rename(workerPath + '.tmp', workerPath);
await writeFile(path.join(dist, '.openai/hosting.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Built Worker with ${Object.keys(assets).length} local assets (${Math.round(Buffer.byteLength(source) / 1024)} KB).`);
